import assert from 'node:assert/strict';
import {prepareMapImage,transitionMap} from '../app/map-transitions.ts';
const pending=new Map();
globalThis.Image=class {decode(){return new Promise((resolve,reject)=>pending.set(this.src,{resolve,reject}))}};
globalThis.document={querySelectorAll:()=>[]};
globalThis.matchMedia=()=>({matches:false});
let scene='world';
const first=transitionMap(()=>scene='old-country','/old.webp');
const latest=transitionMap(()=>scene='continent','/new.webp');
pending.get('/new.webp').resolve();await latest;
pending.get('/old.webp').resolve();await first;
assert.equal(scene,'continent','A late image cannot replace a newer navigation');
assert.equal(prepareMapImage('/new.webp'),prepareMapImage('/new.webp'),'Decoded terrain is cached');
const failed=transitionMap(()=>scene='fallback','/missing.webp');
pending.get('/missing.webp').reject(new Error('missing'));await failed;
assert.equal(scene,'fallback','An unavailable image does not trap navigation');
let snapshots=0;document.startViewTransition=()=>{snapshots++;throw new Error('Do not snapshot the whole map')};
await transitionMap(()=>scene='immediate');assert.equal(scene,'immediate');assert.equal(snapshots,0,'Controls do not create full-screen snapshots');
matchMedia=()=>({matches:true});
await transitionMap(()=>scene='reduced');assert.equal(scene,'reduced','Reduced motion updates without animation');
console.log('PASS: map navigation races, image caching/failure, interrupted transitions, and reduced motion.');

let detailReady;const geometry=new Promise(resolve=>detailReady=resolve);
const detailNavigation=transitionMap(()=>scene='detailed',undefined,geometry);
assert.notEqual(scene,'detailed','Country must not switch before detail geometry loads');
detailReady();await detailNavigation;assert.equal(scene,'detailed');
console.log('PASS: country transitions wait for detailed geography.');
