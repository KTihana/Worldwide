import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import ts from 'typescript';
const source=await readFile(new URL('../app/native.ts',import.meta.url),'utf8');
const javascript=ts.transpileModule(source,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ESNext}}).outputText;
const ids=[];
globalThis.window={fetch:globalThis.fetch,WorldwideNative:{scanQr(id){ids.push(id)}}};
const moduleUrl='data:text/javascript;base64,'+Buffer.from(javascript).toString('base64');
const oldPage=await import(moduleUrl+'#old-page');oldPage.installNativeTransport();
const oldScan=oldPage.scanNativeQr(),oldReply=window.worldwideNativeReply;
const newPage=await import(moduleUrl+'#new-page');newPage.installNativeTransport();
let resolved=false;const newScan=newPage.scanNativeQr().then(value=>{resolved=true;return value});
assert.notEqual(ids[0],ids[1],'New pages must not reuse pending callback identities');
window.worldwideNativeReply(ids[0],{value:'stale result'});
await Promise.resolve();assert.equal(resolved,false,'A late pre-reload response cannot complete a new request');
window.worldwideNativeReply(ids[1],{value:'current result'});
assert.equal(await newScan,'current result');
oldReply(ids[0],{value:''});assert.equal(await oldScan,'','Cancellation stays empty');
console.log('PASS: native callbacks survive reloads without stale replies completing new requests.');
